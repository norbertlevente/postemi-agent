#!/usr/bin/env node
/*
  Writes skills/postemi-templates/reference/*.md from the Postemi web app's
  template library, so the agent skill lists the same templates and hooks as
  the composer's Templates column.

    node scripts/sync-templates.mjs <path to the app's templates folder>
    # e.g. node scripts/sync-templates.mjs ../postemi/src/lib/app/templates

  The folder holds `en.ts` (the words, the source every translation mirrors)
  and `catalog.ts` (groups, sections and the order on screen). Both are
  TypeScript; this script transpiles them with the repository's own
  `typescript` (no type check) and imports the result. It writes:

    reference/index.md         every group, every template: id, title, network, when to use it
    reference/<group>.md       one file per group, the full template bodies

  Run it after the app's templates change, then `pnpm sync:skills` to copy
  the skill into the plugins, and commit the generated files.
*/
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'skills/postemi-templates/reference');

const arg = process.argv[2];
if (!arg) {
  console.error('usage: node scripts/sync-templates.mjs <path to the app templates folder (holds en.ts and catalog.ts)>');
  process.exit(1);
}
let srcDir = resolve(arg);
if (existsSync(srcDir) && !statSync(srcDir).isDirectory()) srcDir = dirname(srcDir);
for (const file of ['en.ts', 'catalog.ts']) {
  if (!existsSync(join(srcDir, file))) {
    console.error(`sync-templates: ${join(srcDir, file)} not found`);
    process.exit(1);
  }
}

/** Transpile one TypeScript file to an ES module in `dir` and import it. */
async function load(file, dir) {
  const source = readFileSync(join(srcDir, file), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, verbatimModuleSyntax: false },
    fileName: file,
  });
  if (/^\s*import\s(?!type\b)/m.test(outputText)) {
    throw new Error(`${file} imports a value; this script expects type-only imports`);
  }
  const out = join(dir, file.replace(/\.ts$/, '.mjs'));
  writeFileSync(out, outputText);
  return import(pathToFileURL(out).href);
}

const tmp = mkdtempSync(join(tmpdir(), 'postemi-templates-'));
let en, catalog;
try {
  en = (await load('en.ts', tmp)).default;
  catalog = await load('catalog.ts', tmp);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const { GROUPS, networkOf } = catalog;
if (!Array.isArray(GROUPS) || typeof networkOf !== 'function' || !en?.groups || !en?.templates) {
  console.error('sync-templates: en.ts or catalog.ts does not have the expected shape (GROUPS, networkOf, groups, templates)');
  process.exit(1);
}

const NETWORK_LABEL = { x: 'X', linkedin: 'LinkedIn' };
const networkLabel = (id) => NETWORK_LABEL[networkOf(id)] ?? 'any network';
/** `hookStories` -> `hook-stories` */
const fileOf = (groupId) => `${groupId.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}.md`;
const oneLine = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').replace(/\|/g, '/').trim();

const HEADER = [
  '<!-- Generated by scripts/sync-templates.mjs from the Postemi app\'s template library (en.ts, catalog.ts). Do not edit by hand: change the app, then run the script again. -->',
  '',
];

const problems = [];
const seen = new Set();
const groups = GROUPS.map((group) => {
  const words = en.groups[group.id];
  if (!words) problems.push(`group ${group.id} has no words in en.ts`);
  const sections = group.sections.map((section) => ({
    title: section.id ? words?.sections?.[section.id] ?? section.id : undefined,
    templates: section.templates.map((id) => {
      const t = en.templates[id];
      if (!t) problems.push(`template ${id} (group ${group.id}) has no words in en.ts`);
      seen.add(id);
      return { id, ...(t ?? { title: id, why: '', body: '' }) };
    }),
  }));
  const ids = new Set(sections.flatMap((s) => s.templates.map((t) => t.id)));
  return { id: group.id, title: words?.title ?? group.id, description: words?.description ?? '', sections, count: ids.size, file: fileOf(group.id) };
});
const unlisted = Object.keys(en.templates).filter((id) => !seen.has(id));
if (problems.length) {
  console.error(`sync-templates: ${problems.length} problem(s)\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const hookGroups = groups.filter((g) => g.id.startsWith('hook'));
const hookCount = new Set(hookGroups.flatMap((g) => g.sections.flatMap((s) => s.templates.map((t) => t.id)))).size;
const total = seen.size;

// One file per group.
mkdirSync(outDir, { recursive: true });
for (const name of readdirSync(outDir)) {
  if (name.endsWith('.md')) rmSync(join(outDir, name));
}
for (const group of groups) {
  const lines = [...HEADER, `# ${group.title}`, '', group.description, '', `${group.count} templates. Square brackets are placeholders: replace every one before you post.`, ''];
  for (const section of group.sections) {
    if (section.title) lines.push(`## ${section.title}`, '');
    const level = section.title ? '###' : '##';
    for (const t of section.templates) {
      lines.push(`${level} ${t.title} (\`${t.id}\`)`, '', `- Network: ${networkLabel(t.id)}`, `- Use it when: ${oneLine(t.why)}`, '', '```text', t.body, '```', '');
    }
  }
  writeFileSync(join(outDir, group.file), `${lines.join('\n').trimEnd()}\n`);
}

// The index.
const index = [
  ...HEADER,
  '# Template index',
  '',
  `${total} templates in ${groups.length} groups, the same ones the Postemi composer shows under Templates. ${hookCount} of them are hooks (the ${hookGroups.length} hook groups). A template can sit in more than one group.`,
  '',
  'Pick from this list, then open the group file for the full text.',
  '',
  '| Group | File | Templates | What it is for |',
  '|---|---|---|---|',
  ...groups.map((g) => `| ${g.title} | [${g.file}](./${g.file}) | ${g.count} | ${oneLine(g.description)} |`),
  '',
];
for (const group of groups) {
  index.push(`## ${group.title} ([${group.file}](./${group.file}))`, '', '| Id | Title | Network | Use it when |', '|---|---|---|---|');
  const listed = new Set();
  for (const section of group.sections) {
    for (const t of section.templates) {
      if (listed.has(t.id)) continue;
      listed.add(t.id);
      index.push(`| \`${t.id}\` | ${oneLine(t.title)} | ${networkLabel(t.id)} | ${oneLine(t.why)} |`);
    }
  }
  index.push('');
}
writeFileSync(join(outDir, 'index.md'), `${index.join('\n').trimEnd()}\n`);

console.log(`sync-templates: ${total} templates (${hookCount} hooks) in ${groups.length} groups -> ${groups.length + 1} files in skills/postemi-templates/reference`);
if (unlisted.length) console.warn(`sync-templates: in en.ts but in no group (not written): ${unlisted.join(', ')}`);
